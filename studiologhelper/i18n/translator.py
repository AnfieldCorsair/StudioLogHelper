class Translator:
    def __init__(self, lang: str = DEFAULT_LANG, locales_dir: str | Path | None = None):
        self._lang = lang if lang in LANGS else DEFAULT_LANG
        self._tables: dict[str, dict[str, str]] = {"ru": _RU, "en": _EN}
        if locales_dir:
            self._load_external(locales_dir)

    def _load_external(self, locales_dir: Path | str):
        dir_path = Path(locales_dir)
        if not dir_path.exists():
            return
        for lang_code in LANGS:
            jf = dir_path / f"{lang_code}.json"
            if jf.exists():
                try:
                    data = json.loads(jf.read_text(encoding="utf-8"))
                    if isinstance(data, dict):
                        # Merge over builtin — external overrides
                        self._tables[lang_code] = {**self._tables.get(lang_code, {}), **data}
                except Exception:
                    continue

    def set_lang(self, code: str):
        if code in LANGS:
            self._lang = code

    def get_lang(self) -> str:
        return self._lang

    def tr(self, key: str, **kwargs) -> str:
        table = self._tables.get(self._lang, self._tables[DEFAULT_LANG])
        s = table.get(key)
        if s is None:
            s = self._tables[DEFAULT_LANG].get(key, key)
        if kwargs:
            try:
                return s.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return s
        return s
